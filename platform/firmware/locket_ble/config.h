// ---- Recordings on the card -----------------------------------------------------------------------------------
// A meeting is many parts, all sent to the phone as one Bluetooth session. A part can be sent only once it is closed.
// It used to be five minutes: nothing reached the phone until the first part closed, so a short meeting only started
// to be sent after it ended. Now the first kLiveParts parts are kDefaultSegmentSeconds long (30 minutes of a meeting
// in one-minute parts), so the audio crosses Bluetooth while people are still talking; every part after that is
// kLongPartFactor times longer, so a very long meeting still fits the sender's part slots (askble::kMaxParts: 30
// short parts plus the long ones cover about six hours). Not run on a board.
//
// 2026-11-18, the owner's decision: record first, send when the recording is DONE. The locket no longer sends while it
// records (sender.cpp waits until the recording has stopped: no Bluetooth traffic competes with the card writes, and
// nothing can stall mid-recording), and every part is five minutes (kLiveParts 0: all parts are kLongPartFactor times
// kDefaultSegmentSeconds), so a recording under five minutes is ONE part, one item on the website, with its own
// transcript, summary and audio. Six hours is 72 parts, within askble::kMaxParts.
constexpr uint32_t kDefaultSegmentSeconds = 60;
constexpr uint32_t kLiveParts = 0;
constexpr uint32_t kLongPartFactor = 5;
constexpr uint32_t kDefaultMaxClipSeconds = 600;
constexpr uint32_t kDefaultMaxUploadBytes = 25u * 1024 * 1024;
constexpr const char* kDirRecording = "/recording";  // a part being written
constexpr const char* kDirPending = "/pending";      // finished parts waiting for the phone
constexpr const char* kDirRejected = "/rejected";    // parts that cannot be read back, kept for diagnosis
constexpr const char* kDirUntimed = "/untimed";      // parts recorded before the clock was set
constexpr uint64_t kMinFreeBytes = 8ull * 1024 * 1024;
// The phone may be away for days: the card's free space is the real limit.
constexpr uint32_t kMaxPendingParts = 5000;
constexpr uint32_t kMinClipBytes = kBytesPerSecond / 2;

// ---- Bluetooth ------------------------------------------------------------------------------------------------
// AUDIO frames are 16 ms of audio each: up to kSendBurst frames at a time, then a pause of kSendIntervalMs; when the
// Bluetooth stack's buffers are full it waits kSendRetryMs and tries that frame again. The values are ONE frame every
// 8 ms and a 50 ms back-off, the pace the locket was proven with (at most twice real time). On 2026-11-17 this was
// changed to bursts of 4 frames and a 15 ms retry to go faster, and on a real locket the transfer then stalled at
// frame 65 for ever: the stack's buffers stayed full, so the phone's confirmations (which need buffers too) did not
// get through. Do not raise kSendBurst or lower kSendRetryMs without testing on a board with the phone app.
//
// 2026-11-17 (a 6 second recording stalled at frame 224 and the meeting was sent again): the locket now also keeps
// at most kSendWindowFrames frames in flight beyond what the phone last confirmed (the phone confirms every 32), so
// the stack's buffers can never fill with audio waiting for a confirmation, whatever the radio does. The pace is
// one frame every 12 ms (about 1.3 times real time) instead of 8.
constexpr uint32_t kSendBurst = 1;
constexpr uint32_t kSendIntervalMs = 12;
constexpr uint32_t kSendRetryMs = 50;
constexpr uint32_t kSendWindowFrames = 96;
// 2026-11-18, from a real recording: "the phone went quiet" at frame 33, then "NimBLE: ble_att_svr_pkt rc=6" (rc 6 is
// "out of memory"). The audio frames fill the Bluetooth stack's few small buffers, so the stack has none left to receive
// the phone's confirmation, which is then lost. So frames are only handed to the stack while at least kMbufReserve
// buffers are free (the phone's writes always find room), and the locket asks the phone for a faster link: audio
// needs about 8.2 KB/s, and a slow link (50 ms between exchanges, two packets each) carries less than that, so the
// queue could only grow.
constexpr int kMbufReserve = 6;
constexpr uint16_t kConnIntervalMin = 12;          // in 1.25 ms steps: 15 ms
constexpr uint16_t kConnIntervalMax = 24;          // 30 ms
constexpr uint16_t kConnLatency = 0;               // answer every exchange
constexpr uint16_t kConnSupervisionTimeout = 400;  // in 10 ms steps: a lost link is noticed after 4 s
constexpr uint32_t kStatusEveryMs = 2000;
// A new pairing number (and so a new code) at least this often, and after every pairing attempt.
constexpr uint32_t kNonceRotateMs = 600000;
constexpr uint32_t kUnpairedLinkMs = 300000;  // a device connected this long without pairing is dropped
constexpr uint16_t kRequestedMtu = 185;

