"""Operator commands for the API.

Run from ``platform/api`` with ``python -m app.cli <command>``.

Commands:
    generate-env       Write a local .env file with a fresh random secret.
    check              Validate configuration, database, and storage.
    bootstrap          Create a company and its first administrator.
    reset-password     Set a new password for a locked-out account.
    housekeeping       Run one pass of periodic upkeep.
    ai-check           Show available processing-provider capabilities.
    calibrate-speakers Choose the speaker-matching threshold from recordings.
    process-file       Run the pipeline on one WAV file outside the database.
"""

from __future__ import annotations

import argparse
import getpass
import secrets
import sys
from pathlib import Path

from app.config import API_DIR, Settings, get_settings

ENV_FILE = API_DIR / ".env"


def generate_env(force: bool) -> int:
    """Write local development settings with a newly generated secret."""
    if ENV_FILE.exists() and not force:
        print(f"{ENV_FILE} already exists. Use --force to replace it.", file=sys.stderr)
        return 1

    lines = [
        "# Local development settings, generated by `python -m app.cli generate-env`.",
        "# This file is gitignored. Never commit it or paste its contents anywhere.",
        "ASK_ENV=development",
        f"ASK_SECRET_KEY={secrets.token_urlsafe(48)}",
        "ASK_EMAIL_BACKEND=console",
        "# The web app proxies API calls, so the client address arrives in X-Forwarded-For.",
        "ASK_TRUST_FORWARDED_FOR=true",
        "ASK_WEB_ORIGINS=http://localhost:3000",
        "ASK_WEB_BASE_URL=http://localhost:3000",
        "",
    ]
    ENV_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {ENV_FILE} with a new secret key (not shown).")
    return 0


def check(settings: Settings) -> int:
    """Validate application settings, database migrations, and storage access."""
    from sqlalchemy import inspect, text

    from app.db import make_engine
    from app.services.storage import Storage

    print(f"environment      : {settings.env}")
    print(f"database         : {'SQLite (development only)' if settings.is_sqlite else 'PostgreSQL'}")

    engine = make_engine(settings.database_url)
    try:
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))

        if not inspect(engine).has_table("alembic_version"):
            print("migrations       : NOT APPLIED (run: python -m alembic upgrade head)")
            return 1

        print("migrations       : applied")
        storage = Storage(settings.storage_dir)
        writable = storage.is_writable()
        print(f"storage          : {'writable' if writable else 'NOT WRITABLE'}")
        print(f"cookies secure   : {settings.secure_cookies}")
        print(f"email backend    : {settings.email_backend}")
        return 0 if writable else 1
    finally:
        engine.dispose()


def read_password(from_stdin: bool) -> str | None:
    """Read a password from a hidden prompt or standard input.

    PowerShell 5.1 can add a byte-order mark to piped input. Strip it so it
    doesn't become part of the password and prevent later sign-in.
    """
    if from_stdin:
        return sys.stdin.readline().rstrip("\r\n").lstrip("\ufeff")

    password = getpass.getpass("Password (12+ characters): ")
    repeated_password = getpass.getpass("Repeat password: ")
    if repeated_password != password:
        print("The passwords do not match.", file=sys.stderr)
        return None
    return password


def bootstrap(settings: Settings, company: str, name: str, email: str, password_stdin: bool) -> int:
    """Create a company and its first administrator account."""
    from app.db import make_engine, make_session_factory
    from app.errors import ApiError
    from app.services import accounts

    password = read_password(password_stdin)
    if password is None:
        return 1

    engine = make_engine(settings.database_url)
    try:
        with make_session_factory(engine)() as db:
            try:
                created, user = accounts.create_company_with_admin(
                    db,
                    company_name=company,
                    email=email,
                    name=name,
                    password=password,
                )
            except ApiError as error:
                print(f"Could not create the account: {error.message}", file=sys.stderr)
                return 1
    finally:
        engine.dispose()

    print(f"Created company '{created.name}' with administrator {user.email}. You can sign in now.")
    return 0


def reset_password(settings: Settings, email: str, password_stdin: bool) -> int:
    """Reset a locked-out administrator's password and revoke existing sessions."""
    from sqlalchemy import select

    from app.db import make_engine, make_session_factory
    from app.errors import ApiError
    from app.models import User
    from app.security.passwords import hash_password
    from app.services import accounts
    from app.services.audit import record_audit

    password = read_password(password_stdin)
    if password is None:
        return 1

    engine = make_engine(settings.database_url)
    try:
        with make_session_factory(engine)() as db:
            user = db.scalar(select(User).where(User.email == accounts.normalize_email(email)))
            if user is None:
                print("No account with that email exists.", file=sys.stderr)
                return 1

            try:
                accounts.require_good_password(password, user.email)
            except ApiError as error:
                print(f"Could not change the password: {error.details or error.message}", file=sys.stderr)
                return 1

            user.password_hash = hash_password(password)
            user.is_active = True
            accounts.revoke_user_sessions(db, user.id)
            membership = accounts.primary_membership(db, user.id)
            record_audit(
                db,
                action="auth.password_reset_by_operator",
                company_id=membership.company_id if membership else None,
                actor_user_id=None,
                object_type="user",
                object_id=user.id,
            )
            db.commit()
    finally:
        engine.dispose()

    print(f"Password changed for {accounts.normalize_email(email)}. Existing sessions were ended.")
    return 0


def ai_check(settings: Settings, load: bool) -> int:
    """Report provider capabilities and optionally run a lightweight model smoke test."""
    from app.ai.registry import build_provider, capabilities
    from app.ai.smoke import smoke_test
    from app.ai.types import ProviderUnavailableError

    caps = capabilities(settings)

    def show_capability(label: str, available: bool) -> None:
        status = "yes" if available else "NO"
        print(f"{label:<20}: {status}")

    provider_note = "  (PLACEHOLDER: output is not real)" if caps.placeholder else ""
    print(f"{'provider':<20}: {caps.provider}{provider_note}")
    show_capability("transcription", caps.transcription)
    show_capability("speaker separation", caps.diarization)
    show_capability("speaker matching", caps.speaker_matching)

    for note in caps.notes:
        print(f"  - {note}")

    if not caps.transcription:
        return 1
    if not load:
        print("\nNothing was loaded. Add --load to run each model once on a generated tone.")
        return 0

    try:
        provider = build_provider(settings)
    except ProviderUnavailableError as error:
        print(f"\nCannot start: {error}", file=sys.stderr)
        return 1

    print("\nLoading and running each model (the first run may download weights)...")
    failed = False
    for result in smoke_test(provider):
        status = "ok  " if result.ok else "FAIL"
        print(f"  {status} {result.name}: {result.detail} ({result.seconds:.1f}s)")
        failed = failed or not result.ok
    return 1 if failed else 0


def calibrate_speakers(settings: Settings, samples: Path, max_false_accept_rate: float) -> int:
    """Recommend a speaker-matching threshold from labeled sample recordings."""
    from app.ai.registry import build_provider
    from app.ai.types import ProviderUnavailableError
    from app.services.calibration import calibrate_directory

    try:
        provider = build_provider(settings)
    except ProviderUnavailableError as error:
        print(f"Cannot start: {error}", file=sys.stderr)
        return 1

    if provider.embedder is None:
        print("This provider has no speaker model, so there is nothing to calibrate.", file=sys.stderr)
        return 1

    try:
        report = calibrate_directory(provider.embedder, samples, max_false_accept_rate)
    except ValueError as error:
        print(f"Cannot calibrate: {error}", file=sys.stderr)
        return 1

    result = report.result
    print(f"People: {report.people}   samples: {report.samples}")
    print(f"Pairs of the same person: {result.same_pairs}   of different people: {result.different_pairs}")
    print(f"Suggested threshold: {result.threshold:.3f}")
    print(f"  wrongly matched others: {result.false_accept_rate:.1%} (target {max_false_accept_rate:.1%})")
    print(f"  real matches missed:    {result.false_reject_rate:.1%}")
    print(f"Currently configured: {settings.speaker_match_threshold:.3f}")

    for warning in report.warnings:
        print(f"WARNING: {warning}")

    print(f"\nTo use it, set  ASK_SPEAKER_MATCH_THRESHOLD={result.threshold:.3f}  and restart the worker.")
    return 0


def process_file(settings: Settings, audio: Path, voices: Path | None, as_json: bool) -> int:
    """Run the processing pipeline on one WAV file without storing it in the database."""
    import json
    from dataclasses import asdict

    from app.ai.registry import build_provider, warm_up
    from app.ai.types import PermanentError, ProviderUnavailableError
    from app.errors import ApiError
    from app.services import offline

    if not audio.is_file():
        print(f"No such file: {audio}", file=sys.stderr)
        return 1

    try:
        # Warm up before processing so model loading isn't included in file timing.
        provider = warm_up(build_provider(settings))
        result = offline.process_file(provider, settings, audio, voices)
    except ApiError as error:
        print(f"Refused: {error.message} ({error.code})", file=sys.stderr)
        return 1
    except (PermanentError, ProviderUnavailableError) as error:
        print(f"Failed: {error}", file=sys.stderr)
        return 1

    if as_json:
        payload = {**asdict(result), "totalSeconds": result.total_seconds}
        print(json.dumps(payload, indent=2))
    else:
        print(offline.render(result))
    return 0


def housekeeping(settings: Settings) -> int:
    """Run one pass of periodic cleanup tasks."""
    from app.db import make_engine, make_session_factory
    from app.services.housekeeping import run_housekeeping
    from app.services.storage import Storage

    engine = make_engine(settings.database_url)
    try:
        results = run_housekeeping(
            make_session_factory(engine),
            settings,
            Storage(settings.storage_dir),
        )
    finally:
        engine.dispose()

    for key, value in results.items():
        print(f"{key}: {value}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    """Build the command-line parser and all subcommands."""
    parser = argparse.ArgumentParser(
        prog="python -m app.cli",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    commands = parser.add_subparsers(dest="command", required=True)

    generate_env_parser = commands.add_parser(
        "generate-env",
        help="write a local .env with a fresh secret",
    )
    generate_env_parser.add_argument(
        "--force",
        action="store_true",
        help="replace an existing .env",
    )

    commands.add_parser("check", help="validate configuration, database and storage")

    bootstrap_parser = commands.add_parser(
        "bootstrap",
        help="create a company and its first administrator",
    )
    bootstrap_parser.add_argument("--company", required=True)
    bootstrap_parser.add_argument("--name", required=True, help="the administrator's full name")
    bootstrap_parser.add_argument("--email", required=True)
    bootstrap_parser.add_argument(
        "--password-stdin",
        action="store_true",
        help="read the password from standard input",
    )

    reset_parser = commands.add_parser(
        "reset-password",
        help="set a new password for a locked-out account",
    )
    reset_parser.add_argument("--email", required=True)
    reset_parser.add_argument(
        "--password-stdin",
        action="store_true",
        help="read the password from standard input",
    )

    commands.add_parser("housekeeping", help="run one pass of periodic upkeep")

    ai_parser = commands.add_parser(
        "ai-check",
        help="show what the processing provider can do on this machine",
    )
    ai_parser.add_argument(
        "--load",
        action="store_true",
        help="also load and run each model once",
    )

    calibration_parser = commands.add_parser(
        "calibrate-speakers",
        help="choose the speaker-matching threshold from samples",
    )
    calibration_parser.add_argument(
        "--samples",
        type=Path,
        required=True,
        help="a folder with one sub-folder of .wav files per person",
    )
    calibration_parser.add_argument(
        "--max-false-accept",
        type=float,
        default=0.01,
        help="how often different people may be wrongly matched, as a fraction (default 0.01)",
    )

    process_parser = commands.add_parser(
        "process-file",
        help="run the processing pipeline on one WAV file by hand, outside the database",
    )
    process_parser.add_argument("audio", type=Path, help="a 16 kHz WAV file")
    process_parser.add_argument(
        "--voices",
        type=Path,
        help="a folder with one sub-folder of .wav samples per person, enrolled in memory for this run only",
    )
    process_parser.add_argument(
        "--json",
        action="store_true",
        help="print the result as JSON",
    )

    return parser


def main(argv: list[str] | None = None) -> int:
    """Parse arguments, load settings as needed, and run the chosen command."""
    args = build_parser().parse_args(argv)

    if args.command == "generate-env":
        return generate_env(args.force)

    settings = get_settings()
    if args.command == "process-file":
        return process_file(settings, args.audio, args.voices, args.json)
    if args.command == "check":
        return check(settings)
    if args.command == "bootstrap":
        return bootstrap(settings, args.company, args.name, args.email, args.password_stdin)
    if args.command == "reset-password":
        return reset_password(settings, args.email, args.password_stdin)
    if args.command == "ai-check":
        return ai_check(settings, args.load)
    if args.command == "calibrate-speakers":
        return calibrate_speakers(settings, args.samples, args.max_false_accept)
    return housekeeping(settings)


if __name__ == "__main__":
    raise SystemExit(main())
